"""Embed the site's OFL fonts as static, Unicode-aware fonts for Worker PDFs.

Run with fontTools and brotli installed. The license files remain in fonts/.
"""
import base64
import io
import json
import zlib
from pathlib import Path
from tempfile import TemporaryDirectory

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.merge import Merger
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]


def embed(family, indexes, weight):
    with TemporaryDirectory() as temporary:
        paths = []
        for index in indexes:
            font = TTFont(ROOT / 'fonts' / f'liza-font-{index}.woff2')
            if 'fvar' in font:
                font = instantiateVariableFont(font, {'wght': weight}, inplace=False)
            # PDF text is positioned explicitly, with no browser shaping tables.
            for table in ('GDEF', 'GPOS', 'GSUB', 'STAT', 'DSIG'):
                if table in font:
                    del font[table]
            font.flavor = None
            target = Path(temporary) / f'{index}.ttf'
            font.save(target)
            paths.append(str(target))
        font = Merger().merge(paths)
        font.flavor = None
        buffer = io.BytesIO()
        font.save(buffer)
        cmap = font.getBestCmap()
        units = font['head'].unitsPerEm
        metric = lambda value: round(value * 1000 / units)
        return {
            'name': family,
            'font': base64.b64encode(buffer.getvalue()).decode('ascii'),
            'cmap': {code: font.getGlyphID(glyph) for code, glyph in cmap.items()},
            'widths': {code: metric(font['hmtx'][glyph][0]) for code, glyph in cmap.items()},
            'bbox': [metric(getattr(font['head'], key)) for key in ('xMin', 'yMin', 'xMax', 'yMax')],
            'ascent': metric(font['hhea'].ascent),
            'descent': metric(font['hhea'].descent),
        }


fonts = {
    'sans': embed('ManropeMedium', [11, 10], 500),
    'serif': embed('CormorantGaramondMedium', [5, 4], 500),
}
target = ROOT / 'tools/customer-portal/backend/voucher-design-fonts.mjs'
target.write_text(
    '// Generated by tools/gift-vouchers/build-pdf-fonts.py from the local website fonts.\n'
    '// Cormorant Garamond and Manrope, SIL Open Font License 1.1; see fonts/*-OFL.txt.\n'
    'export const voucherDesignFonts = ' + json.dumps(fonts, separators=(',', ':')) + ';\n',
    encoding='utf-8',
)
print(f'{target.name}: {target.stat().st_size} bytes')

logo = Image.open(ROOT / 'logo-liza.webp').convert('RGBA')
logo_target = ROOT / 'tools/customer-portal/backend/voucher-brand.mjs'
logo_target.write_text(
    '// Generated from the transparent website logo by build-pdf-fonts.py.\n'
    'export const voucherBrand = ' + json.dumps({
        'width': logo.width,
        'height': logo.height,
        'rgb': base64.b64encode(zlib.compress(logo.convert('RGB').tobytes(), 9)).decode('ascii'),
        'alpha': base64.b64encode(zlib.compress(logo.getchannel('A').tobytes(), 9)).decode('ascii'),
    }, separators=(',', ':')) + ';\n', encoding='utf-8',
)
print(f'{logo_target.name}: {logo_target.stat().st_size} bytes')
